/**
 * Serves a Mini Program project to the simulator: its manifest, the logic-layer
 * bundle, each page's view bundle, its files, a proxy for `wx.request`, and a
 * mock of the WeChat server APIs a backend calls to finish login.
 */
import { closeSync, fstatSync, openSync, readdirSync, readFileSync, realpathSync } from "node:fs";
import { open, readFile, realpath } from "node:fs/promises";
import type { IncomingMessage, ServerResponse } from "node:http";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  compileAppService,
  compilePage,
  loadProject,
  pageWindow,
  type MiniProgramProject,
} from "@omr/compiler";
import {
  FS_FILE_PATH,
  FS_RPC_PATH,
  MemoryFs,
  mockWechatApi,
  PROXY_HEAD_HEADER,
  REQUEST_PROXY_PATH,
  serveFsRequest,
  type Manifest,
  type PackageFiles,
  type ProxyRequest,
  type ProxyResponse,
  type SimulatorConfig,
} from "@omr/runtime";
import { build, type Plugin, type Rolldown, type ViteDevServer } from "vite-plus";
import { createWebViewProxies, isLoopbackAddress } from "./web-view-proxy.ts";

/**
 * Whether a request comes from this machine. The proxies fetch any URL a page
 * names, including the developer's local and private services, so only the
 * machine's own browser (or a port forward to it) may use them, even when the
 * dev server listens on the network.
 */
const fromThisMachine = (req: IncomingMessage) =>
  isLoopbackAddress((req.socket.remoteAddress ?? "").replace(/^::ffff:(?=\d+\.)/, ""));

export interface SimulatorPluginOptions {
  /** The Mini Program project directory. */
  project: string;
}

/** Where the mock WeChat server API is served; a backend uses it in place of https://api.weixin.qq.com. */
export const WECHAT_API_PREFIX = "/__omr/wechat-api";
/** Answers where the shell opens a `<web-view>` page: `{ port, path }` of the proxy for `url`. */
const WEB_VIEW_PROXY_PATH = "/__omr/web-view";
const FILES_PREFIX = "/__omr/files/";
const WECHAT_API_HOST = "api.weixin.qq.com";
const WEBVIEW_ENTRY = path.join(import.meta.dirname, "../src/webview.ts");
const BRIDGE_ENTRY = path.join(import.meta.dirname, "../src/web-view-bridge.ts");
/** The streets of each district, generated by packages/renderer/scripts/generate-regions.ts. */
const REGION_STREETS = path.join(import.meta.dirname, "region-streets.txt");

/**
 * The page of a WebView. It runs in a sandboxed iframe with an opaque origin,
 * which cannot load module scripts from the simulator without CORS, so it loads
 * the view layer as one classic script and gets everything else by message.
 */
const WEBVIEW_HTML = `<!doctype html>
<html lang="zh-CN">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <script src="/__omr/webview.js"></script>
  </head>
  <body></body>
</html>
`;

/** Bundles a browser entry, such as the view layer, into one classic script. */
async function bundleScript(entry: string, sourcemap: boolean): Promise<string> {
  const name = path.basename(entry, ".ts");
  const result = await build({
    configFile: false,
    logLevel: "silent",
    root: path.dirname(entry),
    build: {
      write: false,
      minify: false,
      sourcemap: sourcemap ? "inline" : false,
      lib: { entry, formats: ["iife"], name: "omr", fileName: name },
    },
  });
  const outputs = (Array.isArray(result) ? result : [result]) as Rolldown.RolldownOutput[];
  const chunk = outputs.flatMap((output) => output.output).find((item) => item.type === "chunk");
  if (!chunk || chunk.type !== "chunk") throw new Error(`failed to bundle ${name}`);
  return chunk.code;
}

/** Caches a bundle until `reset`; a failed build is retried on the next call. */
function cachedBundle(entry: string, sourcemap: boolean) {
  let promise: Promise<string> | undefined;
  const get = () => {
    promise ??= bundleScript(entry, sourcemap);
    promise.catch(() => (promise = undefined));
    return promise;
  };
  return Object.assign(get, { reset: () => (promise = undefined) });
}

const CONTENT_TYPES: Record<string, string> = {
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
  ".pdf": "application/pdf",
  ".mp4": "video/mp4",
  ".mp3": "audio/mpeg",
  ".ttf": "font/ttf",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
};

export function omrSimulator(options: SimulatorPluginOptions): Plugin {
  // Codes are single use across the whole session, as on WeChat
  const usedCodes = new Set<string>();
  let projectPromise: Promise<MiniProgramProject> | undefined;
  const project = () => (projectPromise ??= loadProject(options.project));
  // One file system for the server's lifetime, like a device: user files survive page reloads
  let packageRoot: string | undefined;
  const fs = new MemoryFs({ packageFiles: packageFiles(() => packageRoot) });
  const webview = cachedBundle(WEBVIEW_ENTRY, true);
  // Injected inline into web pages, where an inline source map would only weigh them down
  const bridge = cachedBundle(BRIDGE_ENTRY, false);
  const webViewProxies = createWebViewProxies(bridge);
  let streetsPromise: Promise<Map<string, [string, string][]>> | undefined;
  /** Each district's streets, `[code, name]`, read on first use. */
  const regionStreets = () =>
    (streetsPromise ??= readFile(REGION_STREETS, "utf8").then((text) => {
      const map = new Map<string, [string, string][]>();
      for (const line of text.split("\n")) {
        const [district = "", names = ""] = line.split(":");
        if (!district) continue;
        map.set(
          district,
          names.split(",").map((entry) => [district + entry.slice(0, 3), entry.slice(3)]),
        );
      }
      return map;
    }));

  const manifest = async (): Promise<Manifest> => {
    const loaded = await project();
    let config: SimulatorConfig = {};
    for (const dir of new Set([loaded.dir, loaded.root])) {
      const file = path.join(dir, "omr.config.json");
      try {
        config = JSON.parse(await readFile(file, "utf8")) as SimulatorConfig;
        break;
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") {
          throw new Error(`invalid ${file}: ${(error as Error).message}`, { cause: error });
        }
      }
    }
    const windows: Manifest["windows"] = {};
    for (const route of loaded.pages) windows[route] = await pageWindow(loaded, route);
    // The variables of DarkMode are read only when the app supports it, as WeChat does
    let themeVariables: Manifest["themeVariables"];
    const { darkmode, themeLocation } = loaded.appJson;
    if (darkmode === true && typeof themeLocation === "string") {
      const file = path.join(loaded.root, themeLocation);
      try {
        themeVariables = JSON.parse(await readFile(file, "utf8")) as Manifest["themeVariables"];
      } catch (error) {
        throw new Error(`invalid themeLocation ${file}: ${(error as Error).message}`, {
          cause: error,
        });
      }
    }
    return {
      appid: loaded.appid,
      appName: loaded.name,
      appJson: loaded.appJson,
      pages: loaded.pages,
      entryPage: loaded.entryPage,
      windows,
      themeVariables,
      config,
    };
  };

  const handle = async (req: IncomingMessage, res: ServerResponse, url: URL): Promise<boolean> => {
    const { pathname } = url;
    if (pathname === "/__omr/webview.html") {
      send(res, 200, "text/html", WEBVIEW_HTML);
    } else if (pathname === "/__omr/webview.js") {
      send(res, 200, "text/javascript", await webview());
    } else if (
      (pathname === WEB_VIEW_PROXY_PATH || pathname === REQUEST_PROXY_PATH) &&
      !fromThisMachine(req)
    ) {
      sendJson(res, 403, { error: "the simulator's proxies serve only this machine" });
    } else if (pathname === WEB_VIEW_PROXY_PATH) {
      // Where the shell opens a <web-view> page: the proxy for its origin, at the same path
      let target: URL | undefined;
      try {
        target = new URL(url.searchParams.get("url") ?? "");
      } catch {
        // Answered below
      }
      if (!target || !/^https?:$/.test(target.protocol)) {
        sendJson(res, 400, { error: "invalid url" });
      } else {
        const port = await webViewProxies.open(
          target.origin,
          url.searchParams.get("ua") ?? "",
          req.socket.localAddress ?? "localhost",
        );
        sendJson(res, 200, { port, path: `${target.pathname}${target.search}${target.hash}` });
      }
    } else if (pathname === "/__omr/region-streets") {
      const list = (await regionStreets()).get(url.searchParams.get("code") ?? "") ?? [];
      res.writeHead(200, {
        "content-type": "application/json; charset=utf-8",
        "cache-control": "max-age=86400",
        // Asked by the page's sandboxed iframe, whose origin is opaque
        "access-control-allow-origin": "*",
      });
      res.end(JSON.stringify(list));
    } else if (pathname === "/__omr/manifest.json") {
      sendJson(res, 200, await manifest());
    } else if (pathname === "/__omr/app-service.js") {
      send(res, 200, "text/javascript", await compileAppService(await project()));
    } else if (pathname === "/__omr/page.json") {
      sendJson(res, 200, await compilePage(await project(), url.searchParams.get("route") ?? ""));
    } else if (pathname.startsWith(FILES_PREFIX)) {
      await serveFile(
        req,
        res,
        (await project()).root,
        decodeURIComponent(pathname.slice(FILES_PREFIX.length)),
      );
    } else if (pathname === FS_RPC_PATH && req.method === "POST") {
      packageRoot = (await project()).root;
      const body = serveFsRequest(fs, await readBodyBytes(req));
      res.writeHead(200, {
        "content-type": "application/octet-stream",
        "cache-control": "no-store",
      });
      res.end(body);
    } else if (pathname === FS_FILE_PATH) {
      packageRoot = (await project()).root;
      const file = url.searchParams.get("path") ?? "";
      let data: Uint8Array | undefined;
      try {
        data = fs.call("readFile", { path: file }).data;
      } catch {
        // Answered below
      }
      if (!data) {
        sendJson(res, 404, { error: `${file} not found` });
      } else {
        const type =
          CONTENT_TYPES[path.posix.extname(file).toLowerCase()] ?? "application/octet-stream";
        sendBytes(req, res, data, {
          "content-type": type,
          "cache-control": "no-cache",
          "content-security-policy": "sandbox",
        });
      }
    } else if (pathname === REQUEST_PROXY_PATH && req.method === "POST") {
      const request = JSON.parse(await readBody(req)) as ProxyRequest;
      // A request the logic layer gave up on, such as after a timeout, is not finished upstream
      const controller = new AbortController();
      res.on("close", () => {
        if (!res.writableFinished) controller.abort();
      });
      await proxyRequest(request, usedCodes, res, controller.signal);
    } else if (pathname.startsWith(`${WECHAT_API_PREFIX}/`)) {
      const target = new URL(
        pathname.slice(WECHAT_API_PREFIX.length) + url.search,
        `https://${WECHAT_API_HOST}`,
      );
      const response = mockWechatApi(
        { method: req.method ?? "GET", url: target, body: await readBody(req) },
        usedCodes,
      );
      if (response) sendJson(res, response.status, response.json);
      else
        sendJson(res, 404, {
          errcode: -1,
          errmsg: `${target.pathname} is not mocked by the simulator`,
        });
    } else {
      return false;
    }
    return true;
  };

  return {
    name: "omr-simulator",
    configureServer(server: ViteDevServer) {
      server.middlewares.use((req, res, next) => {
        const url = new URL(req.url ?? "/", "http://localhost");
        if (!url.pathname.startsWith("/__omr/")) {
          next();
          return;
        }
        handle(req, res, url).then(
          (handled) => {
            if (!handled) next();
          },
          (error: unknown) => sendJson(res, 500, { error: (error as Error).message }),
        );
      });
      // The view layer is not in the shell's module graph, so watch its sources and rebuild it
      const webviewSources = [
        path.dirname(WEBVIEW_ENTRY),
        ...["@omr/renderer", "@omr/runtime", "@omr/compiler"].map((name) =>
          path.dirname(fileURLToPath(import.meta.resolve(name))),
        ),
      ];
      server.watcher.add(webviewSources);
      server.httpServer?.on("close", () => webViewProxies.close());
      server.watcher.on("change", (file) => {
        if (!webviewSources.some((dir) => file.startsWith(dir + path.sep))) return;
        webview.reset();
        bridge.reset();
        server.ws.send({ type: "full-reload" });
      });
      void project().then(
        (loaded) => {
          server.watcher.add(loaded.dir);
          server.watcher.on("all", (_event, file) => {
            if (!file.startsWith(loaded.dir + path.sep)) return;
            // app.json and project.config.json are read once; reload them too
            projectPromise = undefined;
            server.ws.send({ type: "full-reload" });
          });
          server.config.logger.info(
            `  Mini Program: ${loaded.root}\n  Mock WeChat API: ${WECHAT_API_PREFIX} (use it in place of https://${WECHAT_API_HOST})`,
          );
        },
        (error: unknown) => server.config.logger.error(`[omr] ${(error as Error).message}`),
      );
    },
  };
}

/**
 * Performs `wx.request`, `wx.downloadFile` and `wx.uploadFile` for the logic
 * layer, which cannot make cross-origin requests from the browser. Binary
 * bodies travel as base64; a streamed request gets the body as is, with its
 * status and headers in a response header.
 */
async function proxyRequest(
  request: ProxyRequest,
  usedCodes: Set<string>,
  res: ServerResponse,
  signal: AbortSignal,
): Promise<void> {
  const answer = (head: Omit<ProxyResponse, "body" | "bodyEncoding">, body: Buffer) => {
    if (request.stream) {
      res.writeHead(200, {
        "content-type": "application/octet-stream",
        "cache-control": "no-store",
        [PROXY_HEAD_HEADER]: encodeURIComponent(JSON.stringify(head)),
      });
      res.end(body);
    } else if (request.responseType === "arraybuffer") {
      sendJson(res, 200, { ...head, body: body.toString("base64"), bodyEncoding: "base64" });
    } else {
      sendJson(res, 200, { ...head, body: body.toString("utf8") });
    }
  };
  const body =
    request.body === undefined
      ? undefined
      : request.bodyEncoding === "base64"
        ? Buffer.from(request.body, "base64")
        : request.body;
  try {
    const target = new URL(request.url);
    // A Mini Program cannot call WeChat server APIs itself, but a demo may; answer with the mock
    if (target.host === WECHAT_API_HOST) {
      const mocked = mockWechatApi(
        { method: request.method, url: target, body: body?.toString() },
        usedCodes,
      );
      if (mocked) {
        answer(
          {
            statusCode: mocked.status,
            header: { "content-type": "application/json" },
            cookies: [],
          },
          Buffer.from(JSON.stringify(mocked.json)),
        );
        return;
      }
    }
    const headers = Object.fromEntries(
      Object.entries(request.header).filter(
        ([name]) => !["host", "content-length", "referer"].includes(name.toLowerCase()),
      ),
    );
    const response = await fetch(target, {
      method: request.method,
      headers,
      body: request.method === "GET" || request.method === "HEAD" ? undefined : body,
      signal,
    });
    const head = {
      statusCode: response.status,
      header: Object.fromEntries(response.headers),
      cookies: response.headers.getSetCookie(),
    };
    answer(head, Buffer.from(await response.arrayBuffer()));
  } catch (error) {
    if (signal.aborted) return;
    const cause = (error as Error & { cause?: Error }).cause;
    sendJson(res, 200, { error: cause?.message ?? (error as Error).message });
  }
}

/**
 * The code package files of the project, for `FileSystemManager`: read only,
 * with the checks of `serveFile` (no leaving the root, no dot files, no
 * symlinks out). The file system calls are synchronous, so these reads are too.
 */
function packageFiles(root: () => string | undefined): PackageFiles {
  const resolve = (relative: string): string | undefined => {
    const base = root();
    if (!base || relative.split("/").some((part) => part.startsWith("."))) return undefined;
    const file = path.resolve(base, relative);
    if (file !== base && !file.startsWith(base + path.sep)) return undefined;
    try {
      const [realRoot, realFile] = [realpathSync(base), realpathSync(file)];
      if (realFile !== realRoot && !realFile.startsWith(realRoot + path.sep)) return undefined;
      return realFile;
    } catch {
      return undefined;
    }
  };
  return {
    stat(relative) {
      const file = resolve(relative);
      if (!file) return undefined;
      try {
        const fd = openSync(file, "r");
        try {
          const stats = fstatSync(fd);
          if (!stats.isFile() && !stats.isDirectory()) return undefined;
          return { directory: stats.isDirectory(), size: stats.size, mtimeMs: stats.mtimeMs };
        } finally {
          closeSync(fd);
        }
      } catch {
        return undefined;
      }
    },
    read(relative) {
      const file = resolve(relative);
      if (!file) return undefined;
      try {
        // Check and read the same open file, so it cannot be swapped in between
        const fd = openSync(file, "r");
        try {
          return fstatSync(fd).isFile() ? new Uint8Array(readFileSync(fd)) : undefined;
        } finally {
          closeSync(fd);
        }
      } catch {
        return undefined;
      }
    },
    list(relative) {
      const file = resolve(relative);
      if (!file) return undefined;
      try {
        return readdirSync(file).filter((name) => !name.startsWith("."));
      } catch {
        return undefined;
      }
    },
  };
}

/**
 * Sends a file's bytes, or the one range a `Range` header asks for, as a
 * media element needs to seek; several ranges get the whole file.
 */
export function sendBytes(
  req: IncomingMessage,
  res: ServerResponse,
  body: Uint8Array,
  headers: Record<string, string>,
): void {
  const size = body.byteLength;
  const match = /^bytes=(\d*)-(\d*)$/.exec(req.headers.range?.trim() ?? "");
  if (!match || (match[1] === "" && match[2] === "")) {
    res.writeHead(200, { ...headers, "accept-ranges": "bytes", "content-length": size });
    res.end(body);
    return;
  }
  // `bytes=-n` is the last n bytes
  const start = match[1] === "" ? Math.max(0, size - Number(match[2])) : Number(match[1]);
  const end = match[1] === "" || match[2] === "" ? size - 1 : Math.min(Number(match[2]), size - 1);
  if (start >= size || start > end) {
    res.writeHead(416, { ...headers, "content-range": `bytes */${size}` });
    res.end();
    return;
  }
  res.writeHead(206, {
    ...headers,
    "accept-ranges": "bytes",
    "content-range": `bytes ${start}-${end}/${size}`,
    "content-length": end - start + 1,
  });
  res.end(body.subarray(start, end + 1));
}

async function serveFile(
  req: IncomingMessage,
  res: ServerResponse,
  root: string,
  relative: string,
): Promise<void> {
  const file = path.resolve(root, relative);
  const inside = file.startsWith(root + path.sep);
  if (!inside || relative.split("/").some((part) => part.startsWith("."))) {
    sendJson(res, 403, { error: "forbidden" });
    return;
  }
  try {
    // A symlink must not lead out of the project
    const [realRoot, realFile] = await Promise.all([realpath(root), realpath(file)]);
    if (!realFile.startsWith(realRoot + path.sep)) {
      sendJson(res, 403, { error: "forbidden" });
      return;
    }
    // Check and read the same open file, so it cannot be swapped in between
    const handle = await open(realFile, "r");
    let body: Buffer;
    try {
      if (!(await handle.stat()).isFile()) throw new Error("not a file");
      body = await handle.readFile();
    } finally {
      await handle.close();
    }
    const type = CONTENT_TYPES[path.extname(file).toLowerCase()] ?? "application/octet-stream";
    // Opened as a document, such as an SVG with script, a project file runs in a sandbox, not as the simulator
    sendBytes(req, res, body, {
      "content-type": type,
      "cache-control": "no-cache",
      "content-security-policy": "sandbox",
      // The page's sandboxed iframe has an opaque origin; fonts of @font-face need CORS
      "access-control-allow-origin": "*",
    });
  } catch {
    sendJson(res, 404, { error: `${relative} not found` });
  }
}

function readBodyBytes(req: IncomingMessage): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    req.on("data", (chunk: Buffer) => chunks.push(chunk));
    req.on("end", () => resolve(Buffer.concat(chunks)));
    req.on("error", reject);
  });
}

async function readBody(req: IncomingMessage): Promise<string> {
  return (await readBodyBytes(req)).toString("utf8");
}

function send(res: ServerResponse, status: number, type: string, body: string): void {
  res.writeHead(status, { "content-type": `${type}; charset=utf-8`, "cache-control": "no-cache" });
  res.end(body);
}

function sendJson(res: ServerResponse, status: number, value: unknown): void {
  send(res, status, "application/json", JSON.stringify(value));
}
