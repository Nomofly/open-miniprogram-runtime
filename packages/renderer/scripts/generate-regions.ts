/**
 * Generates the places `<picker mode="region">` offers from China's statistical
 * division codes (National Bureau of Statistics, 2023), as published by
 * https://github.com/modood/Administrative-divisions-of-China (WTFPL):
 *
 * - `src/components/region-data.ts`: provinces, cities and districts, bundled
 *   with the view layer;
 * - `apps/simulator/server/region-streets.txt`: the streets of each district,
 *   which the simulator serves for `level="sub-district"`.
 *
 * Run with `vpx scripts/generate-regions.ts <pcas-code.json>` in packages/renderer.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

interface Division {
  code: string;
  name: string;
  children?: Division[];
}

/** Each province's postcode: the postcode of its capital. */
const PROVINCE_POSTCODES: Record<string, string> = {
  "11": "100000",
  "12": "300000",
  "13": "050000",
  "14": "030000",
  "15": "010000",
  "21": "110000",
  "22": "130000",
  "23": "150000",
  "31": "200000",
  "32": "210000",
  "33": "310000",
  "34": "230000",
  "35": "350000",
  "36": "330000",
  "37": "250000",
  "41": "450000",
  "42": "430000",
  "43": "410000",
  "44": "510000",
  "45": "530000",
  "46": "570000",
  "50": "400000",
  "51": "610000",
  "52": "550000",
  "53": "650000",
  "54": "850000",
  "61": "710000",
  "62": "730000",
  "63": "810000",
  "64": "750000",
  "65": "830000",
};

const source = process.argv[2];
if (!source) throw new Error("usage: generate-regions.ts <pcas-code.json>");
const provinces = JSON.parse(readFileSync(source, "utf8")) as Division[];

const lines: string[] = [];
const streets: string[] = [];
for (const province of provinces) {
  const postcode = PROVINCE_POSTCODES[province.code];
  if (!postcode) throw new Error(`no postcode for ${province.name}`);
  let cities = province.children ?? [];
  // A municipality's districts and counties are listed under the municipality itself
  if (cities.some((city) => city.name === "市辖区")) {
    const districts = cities.flatMap((city) => city.children ?? []);
    cities = [{ code: `${province.code}01`, name: province.name, children: districts }];
  }
  const cityParts = cities.map((city) => {
    const districts = (city.children ?? []).map((district) => {
      const own = district.children ?? [];
      if (own.length > 0) {
        const names = own.map((street) => `${street.code.slice(6)}${street.name}`);
        streets.push(`${district.code}:${names.join(",")}`);
      }
      // Four digits, since a municipality's counties keep their own city digits
      return `${district.code.slice(2, 6)}${district.name}`;
    });
    return `${city.code.slice(2, 4)}${city.name}=${districts.join(",")}`;
  });
  lines.push(`${province.code}${province.name}@${postcode}:${cityParts.join("|")}`);
}

const root = path.join(import.meta.dirname, "..");
writeFileSync(
  path.join(root, "src/components/region-data.ts"),
  `/**
 * Provinces, cities and districts for \`<picker mode="region">\`, generated by
 * scripts/generate-regions.ts from China's statistical division codes (2023).
 * One line per province: \`<code><name>@<postcode>:<city>|<city>\`, each city
 * \`<code><name>=<district>,<district>\`, a city's code being the two digits
 * after the province's and a district's the four.
 */
export const REGION_DATA = ${JSON.stringify(lines.join("\n"))};
`,
);
writeFileSync(
  path.join(root, "../../apps/simulator/server/region-streets.txt"),
  `${streets.join("\n")}\n`,
);
console.log(`${lines.length} provinces, ${streets.length} districts with streets`);
